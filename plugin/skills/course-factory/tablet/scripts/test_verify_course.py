# -*- coding: utf-8 -*-
"""test_verify_course - the order and chain rules of verify_course.py.

    python test_verify_course.py

Pinned:
  * a deck compile_module.py built is one page: it ends on the module check, and the course page leads to the next
    module - no "NO HAND-OFF LAST", no "cannot leave the module" (the factory trial: both on every compiled module);
  * such a deck whose last screen is not the module check, or that links onward, still fails;
  * a deck made by hand keeps the old rules: the check second-to-last, the hand-off last and able to leave the module.
"""
from __future__ import annotations

import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SCRIPT = os.path.join(HERE, "verify_course.py")
sys.stdout.reconfigure(encoding="utf-8", errors="replace")
FAILS = []
HEAD = ("<!DOCTYPE html><html><head><!-- GENERATED by course-factory 2.128.0 compile_module.py from "
        "working_claude/script/M01.json (approved abc) and M01.build.json. --></head><body>")


def check(name, ok, detail=""):
    if not ok:
        FAILS.append(name)
    print(("  ok    " if ok else "  FAIL  ") + name + (("  -> " + str(detail)[-900:]) if detail and not ok else ""))


def slide(kind, body=""):
    return '<section class="slide" data-kind="%s"><div class="slide-body">%s</div></section>' % (kind, body)


def deck(path, html):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as f:
        f.write(html)
    return path


def run(*decks):
    args = [x for i, d in enumerate(decks, 1) for x in ("--deck", "%d=%s" % (i, d))]
    p = subprocess.run([sys.executable, "-I", SCRIPT] + args, capture_output=True, text=True, encoding="utf-8", errors="replace")
    return p.returncode, p.stdout + p.stderr


def main():
    tmp = tempfile.mkdtemp(prefix="verify_course_")
    try:
        one = deck(os.path.join(tmp, "m1", "index.html"), HEAD + slide("Theory") + slide("Summary") + slide("Check") + "</body></html>")
        two = deck(os.path.join(tmp, "m2", "index.html"), HEAD + slide("Theory") + slide("Check") + "</body></html>")
        code, out = run(one, two)
        check("a compiled one-page module ends on its module check and the course page leads on: no NO HAND-OFF LAST, no "
              "'cannot leave the module'", code == 0 and "NO HAND-OFF LAST" not in out and "cannot leave" not in out
              and out.count("check last (one page)") == 2 and out.count("course page") == 2, out)

        bad = deck(os.path.join(tmp, "m3", "index.html"), HEAD + slide("Check") + slide("Theory") + "</body></html>")
        code, out = run(one, bad)
        check("... one whose last screen is not the module check still fails", code == 1 and "NO CHECK LAST" in out, out)
        onward = deck(os.path.join(tmp, "m4", "index.html"), HEAD + slide("Theory") + slide("Check")
                      + '<button id="chainGo" data-next-module="m2">Next module</button></body></html>')
        code, out = run(onward, two)
        check("... and one that links onward fails", code == 1 and "still links onward" in out, out)

        hand = lambda last: "<html><body>" + slide("Theory") + slide("Check") + slide(
            "Hand-off", '<button id="chainGo" type="button" data-next-module="m2">Next</button>' if not last else "") + "</body></html>"
        h1 = deck(os.path.join(tmp, "h1", "index.html"), hand(False))
        h2 = deck(os.path.join(tmp, "h2", "index.html"), hand(True))
        code, out = run(h1, h2)
        check("a deck made by hand keeps the old rules: check second-to-last, hand-off last and able to leave", code == 0
              and out.count("check->handoff ok") == 2, out)
        h3 = deck(os.path.join(tmp, "h3", "index.html"), "<html><body>" + slide("Theory") + slide("Check") + "</body></html>")
        code, out = run(h1, h3)
        check("... and one made by hand that ends on the check is still NO HAND-OFF LAST", code == 1 and "NO HAND-OFF LAST" in out, out)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    print("\n%s" % ("ALL PASS" if not FAILS else "%d FAILED" % len(FAILS)))
    return 1 if FAILS else 0


if __name__ == "__main__":
    sys.exit(main())
